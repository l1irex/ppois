/**
 * @file main.cpp
 * @author Ваше Имя (замените на своё)
 * @brief Тестовая программа с консольным меню для управления Кубиком Рубика.
 * @details Демонстрирует работу класса RubiksCube: создание, перемешивание,
 *          повороты граней, проверку на собранность и загрузку из файла.
 *          Полностью отделяет пользовательский интерфейс от логики класса.
 */

#include <iostream>
#include <string>
#include <limits>       // Для std::numeric_limits (очистка буфера ввода)
#include "RubiksCube.h" // Подключаем наш класс

 // Настройка русской кодировки для Windows
#ifdef _WIN32
#include <windows.h>
#endif

int main() {
    // Устанавливаем кодировку консоли для корректного отображения русского текста
#ifdef _WIN32
    SetConsoleCP(65001);
    SetConsoleOutputCP(65001);
#endif

    // Создаем объект кубика. Конструктор по умолчанию создаст СОБРАННЫЙ кубик.
    RubiksCube cube;
    int choice = -1;

    std::cout << "Добро пожаловать в программу 'Кубик Рубика'!\n";

    // Главный цикл меню
    do {
        std::cout << "\n===============================\n";
        std::cout << "         МЕНЮ ПРОГРАММЫ        \n";
        std::cout << "===============================\n";
        std::cout << "1. Показать текущее состояние кубика\n";
        std::cout << "2. Проверить, собран ли кубик\n";
        std::cout << "3. Перемешать кубик (случайные ходы)\n";
        std::cout << "4. Повернуть конкретную грань\n";
        std::cout << "5. Загрузить состояние кубика из файла\n";
        std::cout << "0. Выход из программы\n";
        std::cout << "-------------------------------\n";
        std::cout << "Выберите действие (0-5): ";

        // === Защита от некорректного ввода (если введут букву вместо числа) ===
        if (!(std::cin >> choice)) {
            std::cin.clear(); // Сбрасываем флаг ошибки
            // Очищаем буфер ввода до конца строки
            std::cin.ignore((std::numeric_limits<std::streamsize>::max)(), '\n');
            std::cout << "Ошибка: введите корректное число!\n";
            continue; // Возвращаемся в начало цикла
        }

        // Обработка выбора пользователя
        switch (choice) {
        case 1: {
            std::cout << "\n";
            std::cout << cube; // Используем перегруженный оператор <<
            break;
        }
        case 2: {
            if (cube.isSolved()) {
                std::cout << "\n[+] Поздравляем! Кубик СОБРАН!\n";
            }
            else {
                std::cout << "\n[-] Кубик НЕ собран. Нужно еще покрутить.\n";
            }
            break;
        }
        case 3: {
            int moves;
            std::cout << "Введите количество случайных ходов (например, 20): ";
            std::cin >> moves;
            if (moves > 0) {
                cube.scramble(moves);
                std::cout << "Кубик успешно перемешан (" << moves << " ходов)!\n";
            }
            else {
                std::cout << "Количество ходов должно быть больше 0.\n";
            }
            break;
        }
        case 4: {
            int face;
            int dir;
            std::cout << "\nИндексы граней: 0-Верх, 1-Низ, 2-Перед, 3-Зад, 4-Лево, 5-Право\n";
            std::cout << "Введите индекс грани для поворота (0-5): ";
            std::cin >> face;

            std::cout << "Введите направление (1 - по часовой, 0 - против часовой): ";
            std::cin >> dir;

            // Проверка корректности введенных данных
            if (face >= 0 && face <= 5 && (dir == 0 || dir == 1)) {
                cube.rotateFace(face, (dir == 1)); // dir == 1 преобразуется в true
                std::cout << "Грань успешно повернута!\n";
            }
            else {
                std::cout << "Ошибка: неверный индекс грани или направление.\n";
            }
            break;
        }
        case 5: {
            std::string filename;
            std::cout << "Введите имя файла для загрузки (например, cube.txt): ";
            std::cin >> filename;

            if (cube.loadFromFile(filename)) {
                std::cout << "Состояние успешно загружено из файла '" << filename << "'\n";
            }
            else {
                std::cout << "Ошибка: не удалось открыть или прочитать файл '" << filename << "'\n";
                std::cout << "Убедитесь, что файл существует и содержит 54 числа через пробел.\n";
            }
            break;
        }
        case 0: {
            std::cout << "\nВыход из программы. До свидания!\n";
            break;
        }
        default: {
            std::cout << "Ошибка: такого пункта меню не существует. Попробуйте снова.\n";
            break;
        }
        }

    } while (choice != 0); // Цикл продолжается, пока пользователь не введет 0

    return 0;
}